//! The command table: for every command id of `keyboardShortcuts.json` its English description and what Webox does with it
//! (`Kind`). Most descriptions are sources of the language pack (context `QObject`); the rest are Webox's own wording. The
//! registry (`mod.rs`) shows them translated.
use crate::{Act, Filter, ListTab, Tab};

/// What a command does in Webox.
#[derive(Clone, Copy)]
pub(crate) enum Kind {
    /// An existing in-app action (`App::act`).
    Run(Act),
    /// Implemented in `shortcuts/commands.rs` (`App::run_cmd`).
    Cmd,
    /// Composer formatting command: emits `Act::Composer(id)`, the composer implements the behaviour.
    Composer,
    /// Handled natively by the focused widget (text editing) or not a key-triggered action; never dispatched here.
    Native,
    /// Webox has no such feature: pressing the key (or choosing it in the search) shows "unavailable".
    Stub,
}

