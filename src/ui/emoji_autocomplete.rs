//! `:name` emoji autocomplete of the composer: the shortcode table and the suggestion popup.
//!
//! Popup: 320 x 192 with a frame inset by 1 px; rows 32 px high, 4 px left / 8 px right margin, 8 px spacing, a 24 px emoji
//! picture, elided text; a scroll bar only while the content overflows. Row colour token `wx-emojiPickerEmoji-background`:
//! dark normal #121212 / hovered #064157 / selected (current) #005E7D, light #FFFFFF / #E5FBFF / #C7F6FF (hover wins over
//! current). View mode `ShortcutOnly` shows the shortcode and the description as a tooltip after 1500 ms;
//! `DescriptionAndShortcut` shows the description with the shortcode as a second (tertiary) line. Webox's choices: at least
//! 2 characters after the colon, at most 60 results (scrolling), view mode ShortcutOnly.
//!
//! Shortcodes: `assets/emoji_shortcodes.tsv` (generated by `scripts/emoji/gen_emoji_shortcodes.py`) holds the English name of
//! every emoji of `assets/emoji_data.tsv` (the pack's emoji names, else the Unicode name); a shortcode is that name in
//! snake_case. When no English name exists the German name is used. A short list of the usual aliases is added.
use crate::*;
use std::sync::OnceLock;

pub(crate) const POPUP_W: f32 = 320.0;
pub(crate) const POPUP_H: f32 = 192.0;
pub(crate) const ROW_H: f32 = 32.0;
pub(crate) const MIN_CHARS: usize = 2;
pub(crate) const MAX_RESULTS: usize = 60;
const TOOLTIP_DELAY: f64 = 1.5;

#[derive(Clone, Copy, PartialEq)]
#[allow(dead_code)]
pub(crate) enum ViewMode { ShortcutOnly, DescriptionAndShortcut }
pub(crate) const VIEW_MODE: ViewMode = ViewMode::ShortcutOnly;

pub(crate) struct Item { pub ch: String, pub code: String, pub en: String, pub de: String, hay_de: String }

/// ASCII snake_case of a name (German umlauts folded).
pub(crate) fn snake(s: &str) -> String {
    let mut out = String::new();
    for c in s.chars().flat_map(|c| c.to_lowercase()) {
        match c {
            'ä' => out.push_str("ae"), 'ö' => out.push_str("oe"), 'ü' => out.push_str("ue"), 'ß' => out.push_str("ss"),
            c if c.is_ascii_alphanumeric() => out.push(c),
            _ => if !out.ends_with('_') && !out.is_empty() { out.push('_') },
        }
    }
    out.trim_end_matches('_').to_string()
}

fn fold(s: &str) -> String { s.to_lowercase().replace('ä', "a").replace('ö', "o").replace('ü', "u").replace('ß', "ss").replace("ae", "a").replace("oe", "o").replace("ue", "u") }

/// Usual aliases.
const ALIASES: [(&str, &str); 16] = [("joy", "😂"), ("smile", "😄"), ("thumbs_up", "👍"), ("thumbs_down", "👎"), ("heart", "❤️"), ("tada", "🎉"), ("fire", "🔥"), ("clap", "👏"),
    ("pray", "🙏"), ("cry", "😢"), ("sob", "😭"), ("wave", "👋"), ("ok_hand", "👌"), ("eyes", "👀"), ("rocket", "🚀"), ("thinking", "🤔")];

pub(crate) fn table() -> &'static Vec<Item> {
    static T: OnceLock<Vec<Item>> = OnceLock::new();
    T.get_or_init(|| build(include_str!("../../assets/emoji_data.tsv"), shortcodes(), &|c| icons::emoji_exists(c)))
}

/// English emoji names: the Webex table when it is in `assets/cisco/`, else the CLDR one.
fn shortcodes() -> &'static str {
    crate::assets::cisco_assets::text("emoji_shortcodes.tsv").unwrap_or(include_str!("../../assets/emoji_shortcodes.tsv"))
}

fn build(data: &str, names: &str, exists: &dyn Fn(&str) -> bool) -> Vec<Item> {
    let mut v: Vec<Item> = Vec::new();
    let mut seen = HashSet::new();
    for (l, n) in data.lines().zip(names.lines()) {
        let mut f = l.split('\t');
        let (_g, _file, ch, de) = (f.next(), f.next(), f.next().unwrap_or(""), f.next().unwrap_or(""));
        let kw = f.next().unwrap_or("");
        let en = n.split('\t').nth(1).unwrap_or("");
        if ch.is_empty() || ch.chars().any(|c| ('\u{1F3FB}'..='\u{1F3FF}').contains(&c)) || !exists(ch) { continue; }
        let code = snake(if en.is_empty() { de } else { en });
        if code.is_empty() || !seen.insert(code.clone()) { continue; }
        v.push(Item { ch: ch.to_string(), code, en: en.to_string(), de: de.to_string(), hay_de: fold(&format!("{de} {}", kw.replace('|', " "))) });
    }
    for (a, ch) in ALIASES {
        if let Some(base) = v.iter().find(|i| i.ch.trim_end_matches('\u{fe0f}') == ch.trim_end_matches('\u{fe0f}')) {
            let it = Item { ch: base.ch.clone(), code: a.to_string(), en: base.en.clone(), de: base.de.clone(), hay_de: base.hay_de.clone() };
            if seen.insert(it.code.clone()) { v.push(it); }
        }
    }
    v
}

/// Suggestions for `query` (the text after the colon): shortcode prefix first, then word prefix, contains, then the German
/// name / keywords. Each emoji once. At most `MAX_RESULTS`.
pub(crate) fn search(query: &str) -> Vec<&'static Item> { search_in(table(), query) }

fn search_in<'a>(all: &'a [Item], query: &str) -> Vec<&'a Item> {
    let q = snake(query);
    let qf = fold(query.trim());
    if q.is_empty() { return vec![]; }
    let mut hits: Vec<(u8, usize, usize, &Item)> = Vec::new();
    for (i, it) in all.iter().enumerate() {
        let rank = if it.code == q { 0 }
            else if it.code.starts_with(&q) { 1 }
            else if it.code.contains(&format!("_{q}")) { 2 }
            else if it.code.contains(&q) { 3 }
            else if it.hay_de.starts_with(&qf) || it.hay_de.contains(&format!(" {qf}")) { 4 }
            else if it.hay_de.contains(&qf) { 5 }
            else { continue };
        hits.push((rank, it.code.len(), i, it));
    }
    hits.sort_by_key(|h| (h.0, h.1, h.2));
    let mut seen = HashSet::new();
    hits.into_iter().filter(|h| seen.insert(h.3.ch.clone())).map(|h| h.3).take(MAX_RESULTS).collect()
}

/// Where the popup goes: above the caret line, left edge at the caret (like a QWidget popup), kept inside the window.
pub(crate) fn popup_pos(caret_top: egui::Pos2, screen: Rect) -> egui::Pos2 {
    let x = caret_top.x.clamp(screen.left() + 8.0, (screen.right() - POPUP_W - 8.0).max(screen.left() + 8.0));
    let y = if caret_top.y - POPUP_H - 4.0 >= screen.top() + 8.0 { caret_top.y - POPUP_H - 4.0 } else { caret_top.y + 24.0 };
    pos2(x, y)
}

/// Draws the popup; returns the index of a clicked row. `sel` is the current row (keyboard), `scroll` brings it into view.
pub(crate) fn popup(ctx: &egui::Context, icons: &mut icons::Icons, t: &Th, pos: egui::Pos2, items: &[&Item], sel: usize, scroll: bool) -> Option<usize> {
    let light = super::menu::light(t);
    let (normal, hover, selected) = if light { (hex(0xFFFFFF), hex(0xE5FBFF), hex(0xC7F6FF)) } else { (hex(0x121212), hex(0x064157), hex(0x005E7D)) };
    let border = if light { alpha(Color32::BLACK, 0.2) } else { alpha(Color32::WHITE, 0.15) }; // wx-popup-widget-border
    let mut clicked = None;
    let outer = Rect::from_min_size(pos, Vec2::new(POPUP_W, POPUP_H));
    egui::Area::new(egui::Id::new("emoji-autocomplete")).fixed_pos(pos).order(egui::Order::Foreground).show(ctx, |ui| {
        ui.allocate_exact_size(outer.size(), Sense::hover()); // the layer must have the popup's size (wheel routing)
        ui.painter().rect_filled(outer, 4.0, normal);
        ui.painter().rect_stroke(outer, 4.0, Stroke::new(1.0_f32, border), egui::StrokeKind::Inside);
        let inner = outer.shrink(1.0);
        let mut c = ui.new_child(egui::UiBuilder::new().max_rect(inner).layout(egui::Layout::top_down(egui::Align::Min)));
        c.set_clip_rect(inner);
        c.spacing_mut().item_spacing = Vec2::ZERO;
        c.spacing_mut().scroll = egui::style::ScrollStyle { bar_width: 8.0, bar_inner_margin: 1.0, bar_outer_margin: 0.0, ..egui::style::ScrollStyle::solid() };
        let overflow = items.len() as f32 * ROW_H > inner.height();
        crate::ui::widgets::vscroll().id_salt("eac-list").max_height(inner.height()).auto_shrink([false, false])
            .scroll_bar_visibility(if overflow { egui::scroll_area::ScrollBarVisibility::AlwaysVisible } else { egui::scroll_area::ScrollBarVisibility::AlwaysHidden })
            .show(&mut c, |ui| {
                ui.spacing_mut().item_spacing = Vec2::ZERO;
                for (i, it) in items.iter().enumerate() {
                    let w = ui.available_width();
                    let (r, resp) = ui.allocate_exact_size(Vec2::new(w, ROW_H), Sense::click());
                    if scroll && i == sel { ui.scroll_to_rect(r, None); }
                    let fill = if resp.hovered() { hover } else if i == sel { selected } else { normal };
                    ui.painter().rect_filled(r, 0.0, fill);
                    icons.emoji(ui, &it.ch, Rect::from_min_size(pos2(r.left() + 4.0, r.center().y - 12.0), Vec2::splat(24.0)));
                    let tx = r.left() + 4.0 + 24.0 + 8.0;
                    let clip = Rect::from_min_max(pos2(tx, r.top()), pos2(r.right() - 8.0, r.bottom()));
                    let p = ui.painter().with_clip_rect(clip);
                    let code = format!(":{}:", it.code);
                    match VIEW_MODE {
                        ViewMode::ShortcutOnly => { p.text(pos2(tx, r.center().y), egui::Align2::LEFT_CENTER, code, FontId::proportional(14.0), t.text1); }
                        ViewMode::DescriptionAndShortcut => {
                            p.text(pos2(tx, r.center().y - 7.0), egui::Align2::LEFT_CENTER, &it.de, FontId::proportional(14.0), t.text1);
                            p.text(pos2(tx, r.center().y + 8.0), egui::Align2::LEFT_CENTER, code, FontId::proportional(12.0), t.text2);
                        }
                    }
                    if resp.hovered() { ctx.set_cursor_icon(egui::CursorIcon::PointingHand); }
                    if resp.clicked() { clicked = Some(i); }
                    // Description as a tooltip after 1500 ms, black balloon style.
                    let hid = egui::Id::new(("eac-hover", i));
                    if VIEW_MODE == ViewMode::ShortcutOnly {
                        let now = ctx.input(|s| s.time);
                        if resp.hovered() {
                            let since: f64 = ctx.data_mut(|d| *d.get_temp_mut_or_insert_with(hid, || now));
                            if now - since >= TOOLTIP_DELAY {
                                egui::Area::new(egui::Id::new("eac-tip")).fixed_pos(pos2(r.left() + 36.0, r.bottom() + 4.0)).order(egui::Order::Tooltip).interactable(false).show(ctx, |ui| {
                                    super::menu::toast_frame(t).show(ui, |ui| ui.label(RichText::new(if it.de.is_empty() { it.en.as_str() } else { it.de.as_str() }).color(t.toast_text).size(13.0)));
                                });
                            } else { ctx.request_repaint_after(std::time::Duration::from_millis(200)); }
                        } else { ctx.data_mut(|d| d.remove::<f64>(hid)); }
                    }
                }
            });
    });
    clicked
}

#[cfg(test)]
mod tests {
    use super::*;
    fn tbl() -> Vec<Item> { build(include_str!("../../assets/emoji_data.tsv"), include_str!("../../assets/emoji_shortcodes.tsv"), &|_| true) }

    #[test]
    fn snake_case() {
        assert_eq!(snake("Face with Tears of Joy"), "face_with_tears_of_joy");
        assert_eq!(snake("Bierkrug & Ärger"), "bierkrug_aerger");
    }

    #[test]
    fn shortcode_search_ranks_prefix_first_and_knows_both_languages() {
        let t = tbl();
        let beer = search_in(&t, "beer");
        assert_eq!(beer[0].code, "beer_mug");
        assert!(search_in(&t, "so").iter().take(5).all(|i| i.code.starts_with("so")));
        assert_eq!(search_in(&t, "joy")[0].code, "joy");
        assert!(search_in(&t, "thumbs").iter().any(|i| i.code == "thumbs_up" || i.code == "thumbsup"));
        // German name / keyword.
        assert!(search_in(&t, "bierkrug").iter().any(|i| i.ch == "🍺"));
        // Contains.
        assert!(search_in(&t, "mug").iter().any(|i| i.code == "beer_mug"));
        // Each emoji once, capped.
        let r = search_in(&t, "face");
        assert!(r.len() <= MAX_RESULTS);
        let mut chars: Vec<&str> = r.iter().map(|i| i.ch.as_str()).collect(); chars.sort(); chars.dedup();
        assert_eq!(chars.len(), r.len());
        assert!(search_in(&t, "").is_empty());
    }
}
